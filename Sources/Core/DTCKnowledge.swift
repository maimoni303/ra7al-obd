import Foundation

/// How safe it is to keep driving with a fault.
enum DriveAdvice: Int, Codable, Comparable {
    case safe = 0, caution = 1, stop = 2
    static func < (a: DriveAdvice, b: DriveAdvice) -> Bool { a.rawValue < b.rawValue }
    var title: String {
        switch self {
        case .safe: return "بأمان"
        case .caution: return "بحذر"
        case .stop: return "لا تسوق"
        }
    }
    var level: AlertLevel {
        switch self {
        case .safe: return .ok
        case .caution: return .warn
        case .stop: return .danger
        }
    }
}

/// How soon the fault needs attention.
enum Urgency: Int, Codable, Comparable {
    case none = 0, watch = 1, soon = 2, now = 3
    static func < (a: Urgency, b: Urgency) -> Bool { a.rawValue < b.rawValue }
    var title: String {
        switch self {
        case .none: return "لا يوجد"
        case .watch: return "تابع"
        case .soon: return "خلال أسبوع"
        case .now: return "فورًا"
        }
    }
}

