    static func generic(_ code: String) -> DTCInfo {
        let c = Array(code.uppercased())
        var system = "نظام غير معروف"
        var drive: DriveAdvice = .caution
        var urgency: Urgency = .soon
        if c.count == 5 {
            let letter = c[0], d1 = c[1], d2 = c[2]
            let fordSpecific = d1 == "1" || d1 == "3"
            switch letter {
            case "P":
                switch d2 {
                case "0", "1": system = "قياس الوقود والهواء"
                case "2": system = "الوقود والهواء — البخاخات"
                case "3": system = "الاحتراق وشمعات التسخين"
                case "4": system = "أنظمة الانبعاثات (EGR و DPF)"
                case "5": system = "السرعة والتباطؤ والحساسات"
                case "6": system = "كمبيوتر المحرك ودوائره"
                case "7", "8", "9": system = "ناقل الحركة (القير)"
                case "A", "B", "C": system = "الهايبرد والدفع"
                default: system = "المحرك"
                }
                if fordSpecific { system += " — كود خاص بفورد" }
            case "C":
                system = "الشاصي (الفرامل ABS والثبات والدركسون)"
            case "B":
                if d1 == "0" && d2 == "0" { system = "الإيرباق وأحزمة الأمان" } else { system = "البودي (الأنوار والأقفال والمكيف)"; drive = .safe; urgency = .watch }
            case "U":
                system = "شبكة اتصال الكمبيوترات"
            default: break
            }
        }
        return DTCInfo(code: code, title: "كود في \(system)",
                       meaning: "هذا الكود يخص \(system). الشرح الدقيق غير موجود في دليل التطبيق.",
                       causes: ["يحتاج قراءة تفصيلية في الورشة أو الوكالة"],
                       action: "سق بحذر وراجع الورشة، وأعرض عليهم رقم الكود.", drive: drive, urgency: urgency, generic: true)
    }
