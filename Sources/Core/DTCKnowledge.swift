    /// Per-cylinder codes (injector circuit, misfire, glow plug) for cylinders 1–8.
    private static func numbered(_ code: String) -> DTCInfo? {
        guard code.count == 5, let n = Int(String(code.last!)), (1...8).contains(n) else { return nil }
        let head = String(code.prefix(4))
        switch head {
        case "P020":
            return DTCInfo(code: code, title: "دائرة بخاخ السلندر \(n)", meaning: "مشكلة كهربائية في دائرة بخاخ السلندر \(n).",
                           causes: ["فيش البخاخ", "سلك البخاخ", "البخاخ"], action: "راجع الورشة؛ السلندر ممكن ما يشتغل.", drive: .caution, urgency: .soon)
        case "P030":
            return DTCInfo(code: code, title: "تقطيع في السلندر \(n)", meaning: "السلندر \(n) ما يحترق بانتظام.",
                           causes: ["بخاخ السلندر \(n)", "ضغط الكمبريشن", "ضغط الديزل"], action: "راجع الورشة. التقطيع المستمر يضر المحرك.", drive: .caution, urgency: .soon)
        case "P067":
            return DTCInfo(code: code, title: "شمعة تسخين السلندر \(n)", meaning: "دائرة شمعة التسخين للسلندر \(n) فيها مشكلة.",
                           causes: ["الشمعة", "السلك", "موديول الشمعات"], action: "التشغيل في البرد يصعب. صلّحها قبل الشتاء.", drive: .safe, urgency: .soon)
        default:
            return nil
        }
    }

